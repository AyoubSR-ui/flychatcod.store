const I18nContext = createContext<I18nContextType | null>(null);

// user.language (when the user is logged in) takes priority over this —
// see LanguageSync in App.tsx, which pushes it in once auth resolves. This
// is just the synchronous initial guess for the first render, before we
// know whether anyone's logged in: localStorage (an explicit past choice
// on this browser) beats the browser's own locale.
function initialLanguage(): Language {
  const stored = localStorage.getItem("flychat_lang");
  if (stored === "en" || stored === "fr") return stored;
  return navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);

  const setLanguage = (lang: Language) => {
    localStorage.setItem("flychat_lang", lang);
    setLanguageState(lang);
  };

  const t = (key: string) => {
    return translations[language][key] || key;
  };

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within an I18nProvider");
  return context;
}
